package com.fleetpilot.vehicle.api.rest;

import java.util.List;
import java.util.UUID;

import com.fleetpilot.common.security.CurrentUser;
import com.fleetpilot.common.security.Roles;
import com.fleetpilot.vehicle.application.DriverAppService;
import com.fleetpilot.vehicle.application.DriverSpaceService;
import com.fleetpilot.vehicle.application.DriverSpaceService.DriverSpace;
import com.fleetpilot.vehicle.application.command.DriverAppCommands.RecordFuel;
import com.fleetpilot.vehicle.application.command.DriverAppCommands.RecordInspection;
import com.fleetpilot.vehicle.application.command.FleetCommands.DeclareIncident;
import com.fleetpilot.vehicle.application.view.DriverAppViews.DriverNotification;
import com.fleetpilot.vehicle.application.view.DriverAppViews.FuelEntryView;
import com.fleetpilot.vehicle.application.view.DriverAppViews.InspectionView;
import com.fleetpilot.vehicle.application.view.DriverAppViews.PhotoView;
import com.fleetpilot.vehicle.application.view.Views.IncidentView;
import com.fleetpilot.vehicle.application.view.Views.VehicleDetail;
import com.fleetpilot.vehicle.domain.model.Photo;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.PositiveOrZero;
import org.springframework.http.HttpHeaders;
import org.springframework.http.HttpStatus;
import org.springframework.http.MediaType;
import org.springframework.security.access.AccessDeniedException;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestHeader;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.ResponseStatus;
import org.springframework.web.bind.annotation.RestController;

/** The space of the connected driver: identified by the {@code driver_id} claim of the token, never by the URL. */
@RestController
@RequestMapping("/api/v1/me")
@PreAuthorize(Roles.DRIVER_ONLY)
@Tag(name = "Driver space", description = "What a driver sees and does in the mobile app")
public class DriverSpaceController {

    /** An odometer reading typed by the driver. */
    public record MileageReport(@NotNull @PositiveOrZero Integer mileage) {
    }

    private final DriverSpaceService space;
    private final DriverAppService app;

    public DriverSpaceController(DriverSpaceService space, DriverAppService app) {
        this.space = space;
        this.app = app;
    }

    @GetMapping
    @Operation(summary = "My profile and my vehicle", description = "With its deadlines and active lease contract")
    public DriverSpace me() {
        return space.space(driverId());
    }

    @PostMapping("/mileage")
    @Operation(summary = "Report the mileage of my vehicle")
    public VehicleDetail reportMileage(@Valid @RequestBody MileageReport report) {
        return space.recordMileage(driverId(), report.mileage());
    }

    @PostMapping("/incidents")
    @ResponseStatus(HttpStatus.CREATED)
    @Operation(summary = "Declare a claim on my vehicle")
    public IncidentView declareIncident(@Valid @RequestBody DeclareIncident declaration) {
        return space.declareIncident(driverId(), declaration);
    }

    @PutMapping("/incidents/{id}")
    @Operation(summary = "Declare a claim with an id generated by the app",
            description = "Sending the same id again returns the claim already declared (offline queue of the app)")
    public IncidentView declareIncident(@PathVariable UUID id, @Valid @RequestBody DeclareIncident declaration) {
        return space.declareIncident(driverId(), id, declaration);
    }

    @PutMapping(path = "/incidents/{id}/photos/{photoId}", consumes = {"image/jpeg", "image/png", "image/webp"})
    @Operation(summary = "Add a photo to my claim", description = "The body is the image itself; at most 2 MB")
    public PhotoView addIncidentPhoto(@PathVariable UUID id, @PathVariable UUID photoId,
            @RequestHeader(HttpHeaders.CONTENT_TYPE) String contentType, @RequestBody byte[] image) {
        return app.addPhoto(driverId(), Photo.Owner.INCIDENT, id, photoId, withoutParameters(contentType), image);
    }

    @GetMapping("/fuel-entries")
    @Operation(summary = "My last fill-ups and charges")
    public List<FuelEntryView> fuelEntries() {
        return app.fuelEntriesOfDriver(driverId());
    }

    @PutMapping("/fuel-entries/{id}")
    @Operation(summary = "Enter a fill-up or a charge", description = "Idempotent: the id is generated by the app")
    public FuelEntryView recordFuel(@PathVariable UUID id, @Valid @RequestBody RecordFuel entry) {
        return app.recordFuel(driverId(), id, entry);
    }

    @GetMapping("/inspections")
    @Operation(summary = "My last inspections")
    public List<InspectionView> inspections() {
        return app.inspectionsOfDriver(driverId());
    }

    @PutMapping("/inspections/{id}")
    @Operation(summary = "Record an inspection of my vehicle", description = "Idempotent: the id is generated by the app")
    public InspectionView recordInspection(@PathVariable UUID id, @Valid @RequestBody RecordInspection inspection) {
        return app.recordInspection(driverId(), id, inspection);
    }

    @PutMapping(path = "/inspections/{id}/photos/{photoId}", consumes = {"image/jpeg", "image/png", "image/webp"})
    @Operation(summary = "Add a photo to my inspection", description = "The body is the image itself; at most 2 MB")
    public PhotoView addInspectionPhoto(@PathVariable UUID id, @PathVariable UUID photoId,
            @RequestHeader(HttpHeaders.CONTENT_TYPE) String contentType, @RequestBody byte[] image) {
        return app.addPhoto(driverId(), Photo.Owner.INSPECTION, id, photoId, withoutParameters(contentType), image);
    }

    @GetMapping("/notifications")
    @Operation(summary = "What I should know", description = "Deadlines due within 30 days or overdue, alerts of the "
            + "box of my vehicle, progress of my claims; most serious first")
    public List<DriverNotification> notifications() {
        return app.notifications(driverId());
    }

    /** "image/jpeg; charset=..." is "image/jpeg". */
    private static String withoutParameters(String contentType) {
        MediaType type = MediaType.parseMediaType(contentType);
        return type.getType() + "/" + type.getSubtype();
    }

    private static UUID driverId() {
        return CurrentUser.driverId().orElseThrow(() -> new AccessDeniedException("The account is not linked to a driver"));
    }
}
