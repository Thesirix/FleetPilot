package com.fleetpilot.vehicle.application;

import java.util.List;
import java.util.Optional;
import java.util.UUID;

import com.fleetpilot.common.error.BusinessRuleException;
import com.fleetpilot.vehicle.application.command.FleetCommands.DeclareIncident;
import com.fleetpilot.vehicle.application.command.VehicleCommands.RecordMileage;
import com.fleetpilot.vehicle.application.view.Views.DriverDetail;
import com.fleetpilot.vehicle.application.view.Views.IncidentView;
import com.fleetpilot.vehicle.application.view.Views.VehicleDetail;
import com.fleetpilot.vehicle.domain.model.Assignment;
import com.fleetpilot.vehicle.domain.model.Incident;
import com.fleetpilot.vehicle.domain.model.MileageSource;
import com.fleetpilot.vehicle.domain.model.Vehicle;
import com.fleetpilot.vehicle.domain.repository.AssignmentRepository;
import com.fleetpilot.vehicle.domain.repository.IncidentRepository;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

/**
 * The driver's own space (Android app and PWA): their profile, the vehicle they currently drive with its deadlines,
 * odometer readings and claim declarations. A driver can only act on the vehicle assigned to them.
 */
@Service
@Transactional
public class DriverSpaceService {

    /** What the driver sees on the home screen of the app. */
    public record DriverSpace(DriverDetail driver, VehicleDetail vehicle) {
    }

    private final DriverService drivers;
    private final VehicleService vehicles;
    private final IncidentService incidents;
    private final AssignmentRepository assignments;
    private final IncidentRepository incidentRepository;

    public DriverSpaceService(DriverService drivers, VehicleService vehicles, IncidentService incidents,
            AssignmentRepository assignments, IncidentRepository incidentRepository) {
        this.drivers = drivers;
        this.vehicles = vehicles;
        this.incidents = incidents;
        this.assignments = assignments;
        this.incidentRepository = incidentRepository;
    }

    @Transactional(readOnly = true)
    public DriverSpace space(UUID driverId) {
        DriverDetail driver = drivers.get(driverId);
        VehicleDetail vehicle = driver.driver().currentVehicle() == null ? null
                : vehicles.get(driver.driver().currentVehicle().id());
        return new DriverSpace(driver, vehicle);
    }

    public VehicleDetail recordMileage(UUID driverId, int mileage) {
        return vehicles.recordMileage(currentVehicle(driverId), new RecordMileage(mileage, null, MileageSource.DRIVER));
    }

    public IncidentView declareIncident(UUID driverId, DeclareIncident declaration) {
        return declareIncident(driverId, UUID.randomUUID(), declaration);
    }

    /** With the id generated by the app: declaring twice the same claim (offline queue replayed) returns the first. */
    public IncidentView declareIncident(UUID driverId, UUID incidentId, DeclareIncident declaration) {
        Optional<Incident> existing = incidentRepository.findById(incidentId);
        if (existing.isPresent()) {
            Incident incident = existing.get();
            if (incident.getDriver() == null || !incident.getDriver().getId().equals(driverId)) {
                throw new BusinessRuleException("ID_ALREADY_USED", "This id is already used by another record");
            }
            return IncidentView.of(incident);
        }
        DeclareIncident asDriver = new DeclareIncident(driverId, declaration.type(), declaration.occurredAt(),
                declaration.location(), declaration.latitude(), declaration.longitude(), declaration.description(),
                declaration.thirdPartyInvolved(), declaration.injuries());
        return incidents.declare(incidentId, currentVehicle(driverId), asDriver);
    }

    /** The vehicle the driver drives today: the only one they can act on. */
    UUID currentVehicle(UUID driverId) {
        drivers.load(driverId);
        return assignments.findByDriverIdInAndEndDateIsNull(List.of(driverId)).stream()
                .map(Assignment::getVehicle)
                .map(Vehicle::getId)
                .findFirst()
                .orElseThrow(() -> new BusinessRuleException("NO_VEHICLE_ASSIGNED", "No vehicle is assigned to you"));
    }
}
